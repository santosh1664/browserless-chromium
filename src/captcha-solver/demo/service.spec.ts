import { expect } from 'chai';
import { SyntheticCaptchaDemoService } from './service.js';
import { solveSyntheticChallenge } from './solver.js';

describe('synthetic CAPTCHA demo', () => {
  it('is disabled by default unless explicitly enabled', () => {
    const service = new SyntheticCaptchaDemoService({ enabled: false });
    expect(() => service.createChallenge()).to.throw(
      'Synthetic CAPTCHA demo is disabled',
    );
  });

  it('creates a synthetic challenge and verifies its generated answer', async () => {
    const service = new SyntheticCaptchaDemoService({ enabled: true });
    const challenge = service.createChallenge();

    expect(challenge.kind).to.equal('arithmetic-demo');
    expect(challenge.prompt).to.match(/^What is \d{1,2} \+ \d{1,2}\?$/);

    const result = await solveSyntheticChallenge(challenge, service);
    expect(result.accepted).to.equal(true);
    expect(result.status).to.equal('verified');
    expect(service.getStatus(challenge.id)?.status).to.equal('verified');
  });

  it('rejects incorrect answers and enforces the attempt limit', () => {
    const service = new SyntheticCaptchaDemoService({
      enabled: true,
      maxAttempts: 2,
    });
    const challenge = service.createChallenge();

    const first = service.verifyAnswer(challenge.id, '999');
    expect(first.accepted).to.equal(false);
    expect(first.status).to.equal('pending');
    expect(first.attemptsRemaining).to.equal(1);

    const second = service.verifyAnswer(challenge.id, '999');
    expect(second.accepted).to.equal(false);
    expect(second.status).to.equal('failed');
    expect(second.attemptsRemaining).to.equal(0);
  });

  it('expires challenges after their TTL', () => {
    const service = new SyntheticCaptchaDemoService({
      enabled: true,
      ttlMs: 1,
    });
    const challenge = service.createChallenge();

    const result = service.verifyAnswer(challenge.id, '1');
    expect(result.status).to.equal('expired');
    expect(result.accepted).to.equal(false);
  });

  it('does not accept a challenge ID that was not generated by the service', () => {
    const service = new SyntheticCaptchaDemoService({ enabled: true });
    const result = service.verifyAnswer('not-a-real-id', '4');

    expect(result.accepted).to.equal(false);
    expect(result.status).to.equal('failed');
  });
});
